export function emojiMatchesQuery(emoji: string, query: string): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  if (emoji.includes(q)) return true;
  const tags = EMOJI_KEYWORDS[emoji] || [];
  return tags.some((tag) => tag.includes(q));
}
