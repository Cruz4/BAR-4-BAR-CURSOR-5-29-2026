'use client';

import { useEffect, useState } from 'react';
import { X } from 'lucide-react';
import { Button } from '@/components/ui/button';

const STORAGE_KEY = 'b4b-cowriter-ai-disclosure-dismissed';

/** One-line AI disclosure for the Co-Writer panel (dismissible per browser). */
export function CoWriterAiDisclosureStrip() {
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    try {
      setVisible(localStorage.getItem(STORAGE_KEY) !== '1');
    } catch {
      setVisible(true);
    }
  }, []);

  if (!visible) return null;

  const dismiss = () => {
    try {
      localStorage.setItem(STORAGE_KEY, '1');
    } catch {
      /* ignore */
    }
    setVisible(false);
  };

  return (
    <div className="flex shrink-0 items-start gap-2 border-b border-white/5 bg-muted/20 px-3 py-2">
      <p className="flex-1 text-[9px] leading-snug text-muted-foreground">
        Suggestions are generated by AI; you&apos;re responsible for what you publish.
      </p>
      <Button
        type="button"
        variant="ghost"
        size="icon"
        className="h-6 w-6 shrink-0"
        onClick={dismiss}
        aria-label="Dismiss AI notice"
      >
        <X className="h-3 w-3" aria-hidden />
      </Button>
    </div>
  );
}
